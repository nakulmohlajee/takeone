import React, { useCallback, useEffect, useState } from 'react';
import { Navbar } from './components/Navbar';
import { Camera, Film, PlayCircle, Sparkles } from 'lucide-react';
import { StartupSplash } from './components/StartupSplash';
import { IdeaInputView } from './components/IdeaInputView';
import { ScriptOverviewView } from './components/ScriptOverviewView';
import { GuidedShootingView } from './components/GuidedShootingView';
import { AiGenerationView } from './components/AiGenerationView';
import { DirectorsCutView } from './components/DirectorsCutView';
import { ImportFootageView } from './components/ImportFootageView';
import { GoogleCloudStackModal } from './components/GoogleCloudStackModal';
import { BigQueryAnalyticsModal } from './components/BigQueryAnalyticsModal';
import { CloudStorageModal } from './components/CloudStorageModal';
import { DEMO_PROJECT_PLANTS } from './components/PreGeneratedDemoData';
import { AppScreen, Project } from './types/director';
import {
  loadProjectLocally,
  saveProjectLocally,
  hydrateProjectMedia,
  clearProjectLocally,
} from './utils/mediaVault';
import { useAutoMatte } from './utils/useAutoMatte';

export default function App() {
  const [showSplash, setShowSplash] = useState(true);
  const [currentScreen, setCurrentScreen] = useState<AppScreen>('idea');
  const [project, setProject] = useState<Project | null>(null);
  const [sessionReady, setSessionReady] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [loadingMessage, setLoadingMessage] = useState('');
  // Scene the user asked to (re)generate from Director's Cut — AiGenerationView scrolls to it
  const [aiFocusSceneId, setAiFocusSceneId] = useState<string | null>(null);
  
  // Modals for Google Cloud stack showcase
  const [showGcpStackModal, setShowGcpStackModal] = useState(false);
  const [showBigQueryModal, setShowBigQueryModal] = useState(false);
  const [showStorageModal, setShowStorageModal] = useState(false);

  // Centralized robust updater that immediately syncs React state and IndexedDB media vault
  const handleUpdateProject = useCallback(
    (next: Project | ((prev: Project) => Project) | ((prev: Project | null) => Project | null)) => {
      setProject((prev) => {
        const updated = typeof next === 'function' ? (next as any)(prev) : next;
        if (updated) {
          void saveProjectLocally(updated, currentScreen);
        }
        return updated;
      });
    },
    [currentScreen]
  );

  // Virtual-background takes are matted on the server in the background, on every screen.
  useAutoMatte(project, handleUpdateProject as (next: (prev: Project) => Project) => void);

  // Handle new script generated by Gemini
  const handleScriptGenerated = (newProject: Project) => {
    const p: Project = { ...newProject, entryPath: newProject.entryPath || 'shoot' };
    setProject(p);
    setCurrentScreen('script-overview');
    void saveProjectLocally(p, 'script-overview');
  };

  const handleImportedProject = (imported: Project) => {
    setProject(imported);
    setCurrentScreen('assembly-review');
    void saveProjectLocally(imported, 'assembly-review');
  };

  // 1-Tap Load Stage Demo (45-second plant love story)
  const handleLoadDemo = () => {
    setProject(DEMO_PROJECT_PLANTS);
    setCurrentScreen('script-overview');
    void saveProjectLocally(DEMO_PROJECT_PLANTS, 'script-overview');
  };

  // Startup: Load from IndexedDB media vault first, rehydrate active media URLs
  useEffect(() => {
    let isMounted = true;
    (async () => {
      try {
        const saved = await loadProjectLocally();
        if (!isMounted) return;
        if (saved.project) {
          const hydrated = await hydrateProjectMedia(saved.project);
          if (!isMounted) return;
          setProject(hydrated);
        }
        if (saved.screen) {
          setCurrentScreen(saved.screen as AppScreen);
        }
      } catch (err) {
        console.warn('Failed restoring local project:', err);
      } finally {
        if (isMounted) setSessionReady(true);
      }
    })();
    return () => {
      isMounted = false;
    };
  }, []);

  // Save whenever project or screen changes
  useEffect(() => {
    if (!sessionReady) return;
    if (project) {
      void saveProjectLocally(project, currentScreen);
    }
  }, [project, currentScreen, sessionReady]);

  useEffect(() => {
    if (!showSplash) return;
    const t = window.setTimeout(() => setShowSplash(false), 4000);
    return () => window.clearTimeout(t);
  }, [showSplash]);

  const handleReset = () => {
    const pId = project?.id;
    setProject(null);
    setCurrentScreen('idea');
    void clearProjectLocally(pId);
  };

  const goToScreen = async (screen: AppScreen) => {
    setCurrentScreen(screen);
    // Capture id for hydrate; merge via functional update so we never overwrite
    // fresher scene state that landed during the await.
    const snapshot = project;
    if (snapshot) {
      void saveProjectLocally(snapshot, screen);
      const hydrated = await hydrateProjectMedia(snapshot);
      setProject((prev) => {
        if (!prev || prev.id !== hydrated.id) return prev;
        const byId = new Map(hydrated.scenes.map((s) => [s.id, s]));
        const mergedScenes = prev.scenes.map((s) => {
          const h = byId.get(s.id);
          if (!h) return s;
          // Prefer durable gcs from either; keep whichever playable URL is newer/non-blob
          const preferUrl = (a?: string, b?: string) => {
            if (a && !a.startsWith('blob:') && !a.startsWith('data:')) return a;
            if (b && !b.startsWith('blob:') && !b.startsWith('data:')) return b;
            return a || b;
          };
          return {
            ...h,
            ...s,
            gcsObjectPath: s.gcsObjectPath || h.gcsObjectPath,
            userRecordedVideoUrl: preferUrl(s.userRecordedVideoUrl, h.userRecordedVideoUrl),
            userInsertUrl: preferUrl(s.userInsertUrl, h.userInsertUrl),
            mimeType: s.mimeType || h.mimeType,
          };
        });
        return { ...prev, scenes: mergedScenes };
      });
    }
  };

  const emptyState = (title: string, body: string) => (
    <div className="max-w-lg mx-auto px-4 py-16 text-center space-y-4">
      <h2 className="text-xl font-extrabold text-[#202124]">{title}</h2>
      <p className="text-sm text-[#5F6368] leading-relaxed">{body}</p>
      <div className="flex flex-col sm:flex-row items-center justify-center gap-2">
        <button
          type="button"
          onClick={() => setCurrentScreen('idea')}
          className="px-4 py-2.5 rounded-xl bg-[#1A73E8] text-white text-sm font-bold cursor-pointer"
        >
          Back to Idea
        </button>
        <button
          type="button"
          onClick={handleLoadDemo}
          className="px-4 py-2.5 rounded-xl bg-white border border-[#DADCE0] text-[#1A73E8] text-sm font-bold cursor-pointer"
        >
          Load Stage Demo
        </button>
      </div>
    </div>
  );

  // Re-film a specific scene from assembly review
  const handleRetakeScene = (sceneId: string) => {
    setProject((prev) => (prev ? { ...prev, lastShootingSceneId: sceneId } : prev));
    setCurrentScreen('guided-shooting');
  };

  // Re-generate a specific AI scene from assembly review
  const handleRegenerateAiScene = (sceneId: string) => {
    setAiFocusSceneId(sceneId);
    setCurrentScreen('ai-generation');
  };

  return (
    <div
      className={`${
        currentScreen === 'guided-shooting'
          ? 'h-[100dvh] overflow-hidden md:min-h-screen md:h-auto md:overflow-x-hidden'
          : 'min-h-screen overflow-x-hidden'
      } bg-[#F8F9FA] text-[#202124] flex flex-col font-['Plus_Jakarta_Sans',sans-serif]`}
    >
      {/* Animated Director's Chair & Clapperboard Startup Splash */}
      {showSplash && (
        <StartupSplash onComplete={() => setShowSplash(false)} />
      )}

      <Navbar
        currentScreen={currentScreen}
        setScreen={goToScreen}
        onLoadDemo={handleLoadDemo}
        onReset={handleReset}
        onReplaySplash={() => setShowSplash(true)}
        projectTitle={project?.title}
        onOpenGcpStack={() => setShowGcpStackModal(true)}
        onOpenBigQuery={() => setShowBigQueryModal(true)}
        onOpenStorage={() => setShowStorageModal(true)}
      />

      <main
        className={`flex-1 min-w-0 pb-20 md:pb-16 ${
          currentScreen === 'guided-shooting'
            ? 'min-h-0 overflow-hidden flex flex-col md:overflow-x-hidden'
            : 'overflow-x-hidden'
        }`}
      >
        {currentScreen === 'idea' && (
          <IdeaInputView
            onScriptGenerated={handleScriptGenerated}
            onImportFootage={() => setCurrentScreen('import-footage')}
            isLoading={isLoading}
            setIsLoading={setIsLoading}
            loadingMessage={loadingMessage}
            setLoadingMessage={setLoadingMessage}
          />
        )}

        {currentScreen === 'import-footage' && (
          <ImportFootageView
            onProjectReady={handleImportedProject}
            onCancel={() => setCurrentScreen('idea')}
          />
        )}

        {currentScreen === 'script-overview' &&
          (project ? (
            <ScriptOverviewView
              project={project}
              onUpdateProject={handleUpdateProject}
              onStartShooting={() => setCurrentScreen('guided-shooting')}
              onGoToAiGeneration={() => {
                setAiFocusSceneId(null);
                setCurrentScreen('ai-generation');
              }}
            />
          ) : (
            emptyState(
              'No shots yet',
              'Write an idea or load the Stage Demo first. Shots, Shoot, and Master need a project.'
            )
          ))}

        {currentScreen === 'guided-shooting' &&
          (project ? (
            <GuidedShootingView
              project={project}
              onUpdateProject={handleUpdateProject}
              onFinishShooting={() => setCurrentScreen('assembly-review')}
            />
          ) : (
            emptyState(
              'Nothing to shoot yet',
              'Create a script from Idea or tap Stage Demo, then come back to film.'
            )
          ))}

        {currentScreen === 'ai-generation' &&
          (project ? (
            <AiGenerationView
              project={project}
              onUpdateProject={handleUpdateProject}
              focusSceneId={aiFocusSceneId}
              onProceedToAssembly={() => setCurrentScreen('assembly-review')}
            />
          ) : (
            emptyState(
              'No project to generate',
              'Start from Idea or Stage Demo, then generate AI cutaways.'
            )
          ))}

        {currentScreen === 'assembly-review' &&
          (project ? (
            <DirectorsCutView
              project={project}
              onUpdateProject={handleUpdateProject}
              onRetakeScene={handleRetakeScene}
              onRegenerateAiScene={handleRegenerateAiScene}
              onBackToShooting={() => setCurrentScreen('guided-shooting')}
              onGenerateAiScenes={() => {
                setAiFocusSceneId(null);
                setCurrentScreen('ai-generation');
              }}
            />
          ) : (
            emptyState(
              'No master cut yet',
              'Create or load a project first, then shoot and assemble your cut.'
            )
          ))}
      </main>

      {/* Google Cloud Modals */}
      <GoogleCloudStackModal
        isOpen={showGcpStackModal}
        onClose={() => setShowGcpStackModal(false)}
        onOpenBigQuery={() => setShowBigQueryModal(true)}
        onOpenStorage={() => setShowStorageModal(true)}
      />

      {project && (
        <BigQueryAnalyticsModal
          project={project}
          isOpen={showBigQueryModal}
          onClose={() => setShowBigQueryModal(false)}
        />
      )}

      <CloudStorageModal
        isOpen={showStorageModal}
        onClose={() => setShowStorageModal(false)}
      />

      {/* Persistent Mobile Bottom Navigation for Quick Switching — same icons as the desktop nav. */}
      <nav
        aria-label="Steps"
        className="md:hidden fixed bottom-0 left-0 right-0 z-[60] bg-white px-2 pt-2 flex items-center justify-around min-w-0"
        style={{ paddingBottom: 'max(0.5rem, env(safe-area-inset-bottom))' }}
      >
        {(
          [
            { screen: 'idea', label: 'Idea', Icon: Sparkles },
            { screen: 'script-overview', label: 'Shots', Icon: Film },
            { screen: 'guided-shooting', label: 'Shoot', Icon: Camera },
            { screen: 'assembly-review', label: 'Master', Icon: PlayCircle },
          ] as const
        ).map(({ screen, label, Icon }) => {
          const on = currentScreen === screen;
          return (
            <button
              key={screen}
              type="button"
              onClick={() => goToScreen(screen)}
              aria-current={on ? 'page' : undefined}
              className={`flex flex-col items-center gap-1 min-w-[64px] py-1 text-xs font-semibold cursor-pointer transition-colors active:scale-95 ${
                on ? 'text-[#1A73E8]' : 'text-[#5F6368]'
              }`}
            >
              <Icon className="w-5 h-5" strokeWidth={on ? 2.4 : 2} />
              {label}
            </button>
          );
        })}
      </nav>
    </div>
  );
}
